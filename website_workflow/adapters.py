"""CLI adapters: workers return data; only the orchestrator writes project artifacts."""
from __future__ import annotations

import json
import os
import queue
import shutil
import signal
import subprocess
import threading
import time
from pathlib import Path

from .config import ROOT, ROLES
from .contracts import SCHEMAS, WorkflowError, parse_result, validate
from .storage import digest, read_json, write_json, write_text

TOOLS = {role: ["view_file", "finish"] for role in ROLES}
TOOLS["researchers"] = ["search_web", "read_url_content", "finish"]
TOOLS["orchestrator"] = ["view_file", "grep_search", "list_dir", "run_command", "write_to_file", "replace_file_content", "finish"]


def image_key(path):
    return os.path.normcase(str(Path(path).resolve()))


def image_receipts(events):
    """Derive image evidence from successful native tool events, never model prose."""
    receipts = {}
    for event in events:
        step = event.get("step_update", {})
        info = step.get("tool_info", {})
        if step.get("state") != "DONE" or info.get("name") != "view_file" or info.get("error"):
            continue
        path = info.get("parameters", {}).get("AbsolutePath")
        if not isinstance(path, str) or Path(path).suffix.lower() != ".png":
            continue
        file = Path(path)
        if not file.is_file():
            raise WorkflowError("Viewed screenshot is missing after inspection")
        content = file.read_bytes()
        if not content.startswith(b"\x89PNG\r\n\x1a\n"):
            raise WorkflowError("Screenshot inspection did not reference a PNG image")
        receipts[image_key(file)] = digest(content)
    return receipts


def sync_agents(root=ROOT):
    """Generate native registrations from canonical portable role instructions."""
    paths = []
    for role in (*ROLES, "orchestrator"):
        body = (root / "roles" / role / "AGENTS.md").read_text(encoding="utf-8")
        is_coordinator = role == "orchestrator"
        description = "User-facing coordinator for the local-only website pipeline." if is_coordinator else f"Bounded website workflow {role} worker; returns structured data only."
        header = ["---", f"name: website-{role}", f"description: {description}",
                  "mainAgent: true", f"subagent: {'false' if is_coordinator else 'true'}", "model: inherit", "inheritMcp: false",
                  f"commandExecutionPolicy: {'sandbox' if is_coordinator else 'off'}", "tools:"]
        header += [f"  - {tool}" for tool in TOOLS[role]]
        header += ["---", "", "<!-- Generated by sync-agents. Edit roles/<role>/AGENTS.md, not this copy. -->", "", body]
        path = root / ".agents" / "agents" / f"website-{role}.md"
        write_text(path, "\n".join(header))
        paths.append(path)
    return paths


def stop_process(process):
    if process.poll() is not None:
        return
    if os.name == "nt":
        subprocess.run(["taskkill", "/PID", str(process.pid), "/T", "/F"],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
    else:
        try:
            os.killpg(process.pid, signal.SIGKILL)
        except ProcessLookupError:
            pass
    process.wait(timeout=10)


class Adapter:
    def __init__(self, config):
        self.config = config

    def run(self, role, prompt, workdir, task_id):
        workdir = Path(workdir)
        workdir.mkdir(parents=True, exist_ok=True)
        write_text(workdir / "prompt.txt", prompt)
        write_json(workdir / "schema.json", SCHEMAS[role])
        if self.config["adapter"] == "fixture":
            source = Path(self.config["fixture_dir"]) / f"{task_id}.json"
            return validate(read_json(source), SCHEMAS[role]), {"total_tokens": 0, "fixture": True}
        if self.config["adapter"] == "antigravity":
            return self._agy(role, prompt, workdir)
        return self._command(role, prompt, workdir)

    def _agy(self, role, prompt, workdir):
        executable = shutil.which(self.config.get("executable", "agy"))
        if not executable:
            raise WorkflowError("Antigravity executable not found; run doctor")
        agent_path = ROOT / ".agents" / "agents" / f"website-{role}.md"
        if not agent_path.exists():
            raise WorkflowError("Native agent registrations missing: run sync-agents")
        deny = ["command(*)", "write_file(*)", "execute_url(*)", "mcp(*)"]
        if role != "researchers":
            deny.append("read_url(*)")
        settings = {"toolPermission": "request-review", "permissions": {"deny": deny, "allow": ["read_url(*)"] if role == "researchers" else []}}
        argv = [executable, "--agent", f"website-{role}", "--model", self.config["models"][role],
                "--sandbox", "--settings", json.dumps(settings),
                "--input-format", "stream-json", "--output-format", "stream-json",
                "--json-schema", str((workdir / "schema.json").resolve()),
                "--print-timeout", f"{self.config['task_timeout_seconds']}s"]
        # Feed one NDJSON turn on stdin, then close it. Large build/review briefs
        # must not hit Windows' ~32K command-line limit.
        message = json.dumps({"event": "user", "message": {"content": prompt}}) + "\n"
        events = self._execute(argv, ROOT, workdir, stream=True, stdin=message,
                               allowed_tools=set(TOOLS[role]) | {"finish"})
        initial = [e for e in events if e.get("event") == "init"]
        if len(initial) != 1 or initial[0]["init"].get("model") != self.config["models"][role]:
            raise WorkflowError("Antigravity did not confirm the requested model")
        selected = initial[0]["init"].get("agent")
        if selected and selected != f"website-{role}":
            raise WorkflowError("Antigravity selected an unexpected agent")
        result_events = [e["result"] for e in events if e.get("event") == "result"]
        if len(result_events) != 1 or result_events[0].get("status") != "SUCCESS":
            raise WorkflowError("Antigravity did not return one successful terminal result; inspect task logs")
        result = result_events[0]
        output = result.get("structured_output")
        if output is None:
            output = parse_result(result.get("response", ""))
        validate(output, SCHEMAS[role])
        usage = dict(result.get("usage", {}))
        if role == "reviewer":
            usage["viewed_images"] = image_receipts(events)
            claimed = {image_key(path) for path in output["screenshots_inspected"]}
            if claimed - usage["viewed_images"].keys():
                raise WorkflowError("Reviewer claimed images without successful view_file tool evidence")
        return output, usage

    def _command(self, role, prompt, workdir):
        replacements = {"model": self.config["models"][role], "role": role,
                        "prompt_file": str((workdir / "prompt.txt").resolve()),
                        "schema_file": str((workdir / "schema.json").resolve()),
                        "workdir": str(workdir.resolve())}
        argv = []
        for part in self.config["command"]:
            for key, value in replacements.items():
                part = part.replace("{" + key + "}", value)
            argv.append(part)
        self._execute(argv, workdir, workdir, stream=False, stdin=prompt)
        output = parse_result((workdir / "stdout.txt").read_text(encoding="utf-8"))
        if self.config.get("result_key"):
            for key in self.config["result_key"].split("."):
                if not isinstance(output, dict) or key not in output:
                    raise WorkflowError("Missing configured command result_key")
                output = output[key]
            if isinstance(output, str):
                output = parse_result(output)
        return validate(output, SCHEMAS[role]), {"unreported": True}

    def _execute(self, argv, cwd, workdir, stream, stdin=None, allowed_tools=None):
        """Drain both pipes, bound output/time, kill descendants, and validate init early."""
        kwargs = {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if os.name == "nt" else {"start_new_session": True}
        for kind in ("stdout", "stderr"):
            write_text(workdir / f"{kind}.txt", "")
        try:
            process = subprocess.Popen(argv, cwd=cwd, stdin=subprocess.PIPE if stdin is not None else subprocess.DEVNULL,
                                       stdout=subprocess.PIPE, stderr=subprocess.PIPE, **kwargs)
        except OSError as exc:
            raise WorkflowError(f"Cannot launch agent: {exc}") from exc
        messages = queue.Queue()
        def pump(pipe, kind):
            try:
                while data := pipe.readline(65536):
                    messages.put((kind, data))
            finally:
                messages.put((kind, None))
                pipe.close()
        threads = [threading.Thread(target=pump, args=(process.stdout, "stdout"), daemon=True),
                   threading.Thread(target=pump, args=(process.stderr, "stderr"), daemon=True)]
        for thread in threads:
            thread.start()
        if stdin is not None:
            def send():
                try:
                    process.stdin.write(stdin.encode("utf-8")); process.stdin.close()
                except (BrokenPipeError, OSError):
                    pass
            threading.Thread(target=send, daemon=True).start()
        events, buffers, ended, size = [], {"stdout": bytearray(), "stderr": bytearray()}, set(), 0
        pending = bytearray()
        deadline = time.monotonic() + self.config["task_timeout_seconds"] + 10
        try:
            while len(ended) < 2:
                if time.monotonic() > deadline:
                    raise WorkflowError("Agent timeout; task can be retried with run")
                try:
                    kind, data = messages.get(timeout=0.2)
                except queue.Empty:
                    continue
                if data is None:
                    ended.add(kind)
                    continue
                size += len(data)
                if size > self.config["max_stream_bytes"]:
                    raise WorkflowError("Agent exceeded output byte limit")
                buffers[kind].extend(data)
                # Persist incrementally so a forcibly interrupted parent still
                # leaves useful model/tool evidence for the next agent.
                with (workdir / f"{kind}.txt").open("ab") as trace:
                    trace.write(data)
                if stream and kind == "stdout":
                    pending.extend(data)
                    while b"\n" in pending:
                        line, _, tail = pending.partition(b"\n"); pending = bytearray(tail)
                        self._event(line, events, allowed_tools)
            if stream and pending.strip():
                self._event(pending, events, allowed_tools)
            process.wait(timeout=5)
            if process.returncode:
                raise WorkflowError(f"Agent exited {process.returncode}; inspect {workdir / 'stderr.txt'}")
            stderr = buffers["stderr"].decode("utf-8", errors="replace").lower()
            if "soft-denied" in stderr or "permission denied" in stderr:
                raise WorkflowError("Agent encountered a permission denial; result is not accepted")
            return events
        finally:
            stop_process(process)
            for kind, content in buffers.items():
                write_text(workdir / f"{kind}.txt", content.decode("utf-8", errors="replace"))
            for thread in threads:
                thread.join(timeout=2)

    @staticmethod
    def _event(line, events, allowed_tools=None):
        if not line.strip():
            return
        event = parse_result(line.decode("utf-8"))
        if not isinstance(event, dict):
            raise WorkflowError("Invalid stream event")
        # init.tools advertises the full CLI registry even for restricted custom
        # agents in the tested build. Check actual calls, not this inventory.
        if event.get("event") == "step_update":
            step = event.get("step_update", {})
            info = step.get("tool_info", {})
            name = info.get("name", step.get("tool_name"))
            if name and allowed_tools is not None and name not in allowed_tools:
                raise WorkflowError(f"Worker attempted an unapproved tool: {name}")
            if "permission denied" in json.dumps(info.get("error", {})).lower():
                raise WorkflowError("Worker encountered a denied tool; result is not accepted")
        events.append(event)
